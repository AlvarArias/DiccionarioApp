import Foundation
import SwiftUI


/**
An extension to the Color class that adds custom colors.
Usage: Access the custom colors as static properties on the Color class.
*/
extension Color {
    
    /// A custom orange color.
    static let myOrange = Color("myOrange")
    /// A custom light blue color.
    static let myLightBlue = Color("myLightBlue")
    /// A custom gray color.
    static let myGrey = Color("myGrey")
    /// A custom dark blue color.
    static let myDarkBlue = Color("myDarkBlue")
   
    }


